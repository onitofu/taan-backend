package taan.online.server;

enum ProtocolEvent {
    CHECK_ACCOUNT,
    CREATE_ACCOUNT,
    FIRST_PACKET,
    USER_LOGIN,
    KEEP_ALIVE,
    CONFIRM_NAME,
    NEW_CHARACTER,
    DELETE_CHARACTER,
    SELECT_CHARACTER,
    GET_CHANNEL_LIST,
    UPDATE_CASH,
    CLIENT_LOGGING,
    MOVE_INVENTORY_ITEM,
    INVENTORY_REQUEST_COMPLETED,
    INVENTORY_REQUEST_IGNORED,
    MOVE_TO,
    LOBBY_ENTER,
    LOBBY_LEAVE,
    CHANNEL_MOVED,
    CHANNEL_MOVE_REJECTED,
    CHANNEL_REQUEST_IGNORED,
    LOBBY_ENTERED,
    LOBBY_UNAVAILABLE,
    LOBBY_LEFT_MEMBER,
    LOBBY_LEFT_UNBOUND,
    ACCOUNT_CHECK_COMPLETED,
    REGISTRATION_CREATED,
    REGISTRATION_REJECTED,
    HANDSHAKE_COMPLETED,
    LOGIN_SUCCEEDED,
    LOGIN_REJECTED,
    LOGIN_IGNORED,
    KEEP_ALIVE_ACCEPTED,
    NAME_CHECK_COMPLETED,
    CHARACTER_CREATED,
    CHARACTER_DELETED,
    CHARACTER_REJECTED,
    CHARACTER_REQUEST_IGNORED,
    CHARACTER_SELECTED,
    CHARACTER_SELECTION_REJECTED,
    SELECTED_REQUEST_COMPLETED,
    SELECTED_REQUEST_IGNORED,
    CONNECTION_CLOSED;

    boolean isRequest() {
        return switch (this) {
            case CHECK_ACCOUNT, CREATE_ACCOUNT, FIRST_PACKET, USER_LOGIN, KEEP_ALIVE,
                CONFIRM_NAME, NEW_CHARACTER, DELETE_CHARACTER, SELECT_CHARACTER, GET_CHANNEL_LIST, UPDATE_CASH,
                CLIENT_LOGGING, MOVE_INVENTORY_ITEM, MOVE_TO, LOBBY_ENTER, LOBBY_LEAVE -> true;
            default -> false;
        };
    }
}
